#!/usr/bin/env node
/**
 * Converts a `pg_restore --data-only` COPY stream into a MySQL INSERT script
 * that phpMyAdmin can import.
 *
 * Usage:
 *   pg_restore --data-only --no-owner --no-privileges -f pg-data.sql liquorshop_db.sql
 *   node scripts/pg-dump-to-mysql.mjs pg-data.sql > mysql-data.sql
 *
 * Handles the four ways Postgres COPY text format differs from MySQL literals:
 *   \N        -> NULL
 *   t / f     -> 1 / 0   (for known boolean columns)
 *   \\t \\n \\r \\\\  -> real characters, then re-escaped for MySQL
 *   JSON      -> passed through as a quoted string; MySQL parses it on insert
 */

import { readFileSync } from "node:fs";

/**
 * Boolean columns per table. Postgres COPY emits these as `t`/`f`, which MySQL
 * would otherwise store as the strings "t"/"f" (or reject on a strict server).
 */
const BOOLEAN_COLUMNS = {
  products: ["is_premium", "is_imported", "is_custom"],
  locations: ["pickup_available", "delivery_available"],
  location_inventory: ["featured", "hidden"],
  events: ["active"],
  reviews: ["verified"],
  users: ["active"],
  drivers: ["active"],
};

/** Tables must load parents-before-children to satisfy foreign keys. */
const TABLE_ORDER = [
  "categories",
  "locations",
  "products",
  "users",
  "drivers",
  "location_inventory",
  "events",
  "reviews",
  "orders",
  "order_items",
  "inventory_ledger",
  "activity_logs",
  "role_definitions",
];

function decodeCopyField(raw) {
  if (raw === "\\N") return null;
  let out = "";
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] !== "\\") {
      out += raw[i];
      continue;
    }
    const next = raw[++i];
    if (next === "t") out += "\t";
    else if (next === "n") out += "\n";
    else if (next === "r") out += "\r";
    else if (next === "b") out += "\b";
    else if (next === "f") out += "\f";
    else if (next === "\\") out += "\\";
    else out += next;
  }
  return out;
}

function quote(value) {
  if (value === null) return "NULL";
  return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}

function parseCopyBlocks(text) {
  const lines = text.split("\n");
  const blocks = [];
  let current = null;

  for (const line of lines) {
    if (current) {
      if (line === "\\.") {
        blocks.push(current);
        current = null;
      } else if (line.length) {
        current.rows.push(line.split("\t").map(decodeCopyField));
      }
      continue;
    }
    const match = /^COPY\s+(?:public\.)?"?(\w+)"?\s*\(([^)]*)\)\s+FROM stdin;/.exec(line);
    if (match) {
      current = {
        table: match[1],
        columns: match[2].split(",").map((c) => c.trim().replace(/"/g, "")),
        rows: [],
      };
    }
  }
  return blocks;
}

function emit(blocks) {
  const byTable = new Map(blocks.map((b) => [b.table, b]));
  const ordered = [
    ...TABLE_ORDER.filter((t) => byTable.has(t)),
    ...blocks.map((b) => b.table).filter((t) => !TABLE_ORDER.includes(t)),
  ];

  const out = [
    "-- Generated by scripts/pg-dump-to-mysql.mjs",
    "-- Import into phpMyAdmin AFTER running `prisma migrate deploy` (tables must exist).",
    "SET NAMES utf8mb4;",
    "SET FOREIGN_KEY_CHECKS = 0;",
    "START TRANSACTION;",
    "",
  ];

  for (const table of ordered) {
    const block = byTable.get(table);
    if (!block || !block.rows.length) {
      out.push(`-- ${table}: no rows`, "");
      continue;
    }
    const bools = new Set(BOOLEAN_COLUMNS[table] ?? []);
    const cols = block.columns.map((c) => `\`${c}\``).join(", ");
    out.push(`-- ${table}: ${block.rows.length} row(s)`);
    out.push(`DELETE FROM \`${table}\`;`);

    const values = block.rows.map((row) => {
      const cells = row.map((cell, i) => {
        if (cell === null) return "NULL";
        if (bools.has(block.columns[i])) return cell === "t" ? "1" : "0";
        return quote(cell);
      });
      return `(${cells.join(", ")})`;
    });

    // Chunked so a single statement stays under typical max_allowed_packet.
    for (let i = 0; i < values.length; i += 100) {
      out.push(`INSERT INTO \`${table}\` (${cols}) VALUES`);
      out.push(values.slice(i, i + 100).join(",\n") + ";");
    }
    out.push("");
  }

  out.push("COMMIT;", "SET FOREIGN_KEY_CHECKS = 1;", "");
  return out.join("\n");
}

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/pg-dump-to-mysql.mjs <pg-data.sql>");
  process.exit(1);
}
process.stdout.write(emit(parseCopyBlocks(readFileSync(input, "utf8"))));
